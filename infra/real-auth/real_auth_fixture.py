"""Owned disposable real GoTrue v2.197.0 fixture for the adult backend's real-Auth tests (the adult app only).

Adapted from the read-only reference helper phase4_real_auth_fixture.py: same fixture, with every writable path moved under one
runtime root of this checkout's choosing (AYA_REAL_AUTH_RUNTIME, default <tmp>/aya-real-auth-<uid>), the pinned image reference
embedded, and jose-util built from the already-cached go-jose v4.1.6 instead of taken from another worker's directory.

    python3 -I real_auth_fixture.py build-jose-util                 build the pinned jose-util into the runtime root (offline)
    python3 -I real_auth_fixture.py up [--jose-util PATH] [--jwt-exp SECONDS]   start one fixture; print only non-secret facts
    python3 -I real_auth_fixture.py status RUNTIME_DIR      report one fixture's containers and Auth health
    python3 -I real_auth_fixture.py down RUNTIME_DIR        remove exactly what one fixture's manifest records; if any removal
                                                            fails, the manifest stays so that down can be run again

`up` creates, each labelled aya.fixture=<label>: an internal network holding the pinned PostgreSQL (no host port); a
bridge network on which the pinned GoTrue publishes its API on 127.0.0.1:<free port> only; a dedicated non-superuser
auth owner and database; an ES256 signing key generated by the pinned go-jose jose-util; a service_role admin JWT that
jose-util signs with it; one admin-confirmed synthetic example.test user; and three tokens jose-util signs with Auth's
key that differ from a real access token of that user only in issuer, audience or role. It writes fixture.env (0600),
which the Go tests read through AYA_REAL_AUTH_FIXTURE. Signup stays disabled; no mail, SMS, social or anonymous
provider is configured. Secrets exist only in memory and in the 0700 runtime directory, in 0600 files (jose-util writes
its key files 0400): never in arguments, output or logs. A failed `up` removes every resource it created and every
secret file, keeping only its manifest and redacted container logs. No image is ever pulled; nothing is pruned.

Access tokens of real sessions last GoTrue's default 3600 s. `up --jwt-exp SECONDS` starts a NEW fixture whose GoTrue
issues shorter ones (30 to 3600 s, e.g. 60 for a browser refresh test that waits out a real expiry); `up` then checks
that a real password session carries exactly that lifetime. Fixtures already running are never changed.
"""
