def ensure_runtime():
    """Creates the runtime root and the empty Docker CLI configuration, both 0700, and refuses a root another user owns."""
    for path in (RUNTIME, RUNTIME / 'docker-cli', EVIDENCE):
        path.mkdir(mode=0o700, parents=True, exist_ok=True)
        if path.stat().st_uid != os.getuid():
            raise SystemExit('refusing: the runtime root is not owned by this user')
        os.chmod(path, 0o700)


def now_iso():
    return datetime.datetime.now(datetime.timezone.utc).isoformat()


def docker(*args, input=None, timeout=60):
    return subprocess.run([DOCKER, *args], env=DOCKER_ENV, input=input, text=True, capture_output=True,
                          timeout=timeout)


def require(result, step):
    if result.returncode:
        raise RuntimeError(step + ' failed')
    return result


def wait_for(seconds, ready, failure):
    end = time.monotonic() + seconds
    while time.monotonic() < end:
        if ready():
            return
        time.sleep(1)
    raise RuntimeError(failure)


def envfile(values):
    if any('\n' in value or '\r' in value for value in values.values()):
        raise RuntimeError('an env-file value holds a line break')
    return ''.join(key + '=' + value + '\n' for key, value in values.items())


class _NoRedirect(urllib.request.HTTPRedirectHandler):
    def redirect_request(self, *args, **kwargs):
        return None


_OPENER = urllib.request.build_opener(urllib.request.ProxyHandler({}), _NoRedirect())


def http_json(method, url, body=None, bearer=None, timeout=10):
    """One request to the fixture's loopback Auth: never through a proxy, never following a redirect."""
    data = None if body is None else json.dumps(body).encode()
    request = urllib.request.Request(url, data=data, method=method, headers={'Accept': 'application/json'})
    if data is not None:
        request.add_header('Content-Type', 'application/json')
    if bearer:
        request.add_header('Authorization', 'Bearer ' + bearer)
    try:
        with _OPENER.open(request, timeout=timeout) as response:
            status, raw = response.status, response.read(1 << 20)
    except urllib.error.HTTPError as error:
        status, raw = error.code, error.read(1 << 20)
    except (urllib.error.URLError, OSError):
        return 0, {}
    try:
        return status, json.loads(raw or b'{}')
    except ValueError:
        return status, {}


def jwt_exp(value):
    """The --jwt-exp value: whole seconds in plain decimal digits, within JWT_EXP_RANGE."""
    low, high = JWT_EXP_RANGE
    if not (value.isascii() and value.isdigit() and value == str(int(value)) and low <= int(value) <= high):
        raise argparse.ArgumentTypeError('--jwt-exp takes whole seconds from %d to %d' % JWT_EXP_RANGE)
    return int(value)


def build_jose_util(_args=None):
    """Builds the pinned go-jose v4.1.6 jose-util offline from this checkout's module cache (go.mod pins the version)."""
    ensure_runtime()
    env = dict(os.environ, GOPROXY='off', GOTOOLCHAIN='local')
    result = subprocess.run(['go', 'build', '-o', str(JOSE_UTIL), 'github.com/go-jose/go-jose/v4/jose-util'],
                            cwd=REPO / 'backend', env=env, capture_output=True, text=True, timeout=300)
    if result.returncode or not JOSE_UTIL.is_file():
        raise SystemExit('jose-util could not be built offline from the cached go-jose module')
    print(json.dumps({'jose_util': str(JOSE_UTIL)}))
    return 0


def jose_util(path):
    binary = Path(path)
    if binary.is_dir():
        binary = binary / 'jose-util'
    if not (binary.is_file() and os.access(binary, os.X_OK)):
        raise SystemExit('the pinned jose-util binary was not found; run build-jose-util or pass --jose-util PATH')
    return binary


def jose_sign(binary, key_path, claims):
    """Signs claims as a compact ES256 JWS with jose-util: payload on stdin, token on stdout, nothing in arguments."""
    result = subprocess.run([str(binary), 'sign', '--key', str(key_path), '--alg', 'ES256'],
                            input=json.dumps(claims, separators=(',', ':')), text=True, capture_output=True, timeout=30)
    token = result.stdout.strip()
    if result.returncode or token.count('.') != 2:
        raise RuntimeError('jose-util could not sign a fixture token')
    return token


def claims_of(token):
    """The claims of a token this fixture's own Auth just issued; only copied into wrong-claim tokens."""
    segment = token.split('.')[1]
    return json.loads(base64.urlsafe_b64decode(segment + '=' * (-len(segment) % 4)))


def free_port():
    for _ in range(50):
        with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as probe:
            probe.bind(('127.0.0.1', 0))
            port = probe.getsockname()[1]
        if port not in RESERVED_PORTS:
            return port
    raise RuntimeError('no free loopback port')


def remove(kind, entry, label):
    """Removes one recorded container or network after checking it carries this fixture's label; nothing else."""
    ref = entry.get('id') or entry['name']
    template = '{{index .Config.Labels "aya.fixture"}}' if kind == 'container' else '{{index .Labels "aya.fixture"}}'
    try:
        inspected = docker(kind, 'inspect', '--format', template, ref)
        if inspected.returncode:
            return 'absent'
        if inspected.stdout.strip() != label:
            return 'kept: not labelled for this fixture'
        removal = docker('container', 'rm', '-f', ref) if kind == 'container' else docker('network', 'rm', ref)
    except (subprocess.SubprocessError, OSError):
        return 'removal failed'  # Docker could not be asked: incomplete, so the manifest stays for a retry
    return 'removed' if removal.returncode == 0 else 'removal failed'


class Fixture:
    def __init__(self, private, manifest):
        self.private, self.manifest, self.secrets = private, manifest, []

    @classmethod
    def new(cls):
        ensure_runtime()
        stamp = datetime.datetime.now(datetime.timezone.utc).strftime('%Y%m%dT%H%M%S').lower()
        label = PREFIX + stamp + '-' + secrets.token_hex(3)
        private = RUNTIME / label
        private.mkdir(mode=0o700)
        os.chmod(private, 0o700)
        fixture = cls(private, {'label': label, 'runtime_directory': str(private), 'auth_image': AUTH_IMAGE,
                                'postgres_image': POSTGRES_IMAGE, 'created_at': now_iso(), 'state': 'creating',
                                'containers': [], 'networks': [], 'files': [], 'synthetic_users': []})
        fixture.record()
        return fixture

    @classmethod
    def load(cls, path):
        private = Path(path).resolve(strict=True)
        if private.parent != RUNTIME.resolve() or not private.name.startswith(PREFIX):
            raise SystemExit('refusing: not a runtime directory of this helper')
        manifest = json.loads((private / 'manifest.json').read_text())
        if manifest.get('label') != private.name:
            raise SystemExit('refusing: the manifest does not belong to this directory')
        return cls(private, manifest)

    @property
    def label(self):
        return self.manifest['label']

    def record(self):
        temporary = self.private / 'manifest.json.tmp'
        descriptor = os.open(temporary, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
        with os.fdopen(descriptor, 'w') as handle:
            json.dump(self.manifest, handle, indent=2)
        os.replace(temporary, self.private / 'manifest.json')

    def track(self, name, kind='secret'):
        """Records a file before it exists, so a failure can never leave an untracked secret behind."""
        self.manifest['files'].append({'name': name, 'kind': kind})
        self.record()
        return self.private / name

    def write(self, name, text, kind='secret'):
        path = self.track(name, kind)
        descriptor = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
        with os.fdopen(descriptor, 'w') as handle:
            handle.write(text)
        return path

    def discard(self, name):
        (self.private / name).unlink(missing_ok=True)
        self.manifest['files'] = [entry for entry in self.manifest['files'] if entry['name'] != name]
        self.record()

    def network(self, name, internal):
        entry = {'name': name, 'id': None, 'internal': internal}
        self.manifest['networks'].append(entry)
        self.record()
        args = ['network', 'create', '--label', LABEL + '=' + self.label] + (['--internal'] if internal else []) + [name]
        entry['id'] = require(docker(*args), 'create the owned network ' + name).stdout.strip()
        self.record()
        return name

    def container(self, name, *args):
        entry = {'name': name, 'id': None}
        self.manifest['containers'].append(entry)
        self.record()
        entry['id'] = require(docker(*args), 'create the owned container ' + name).stdout.strip()
        self.record()
        return name

    def redact(self, text):
        for value in sorted({value for value in self.secrets if value}, key=len, reverse=True):
            text = text.replace(value, '[REDACTED_OWNED_FIXTURE_SECRET]')
        return text

    def create(self, jose, jwt_exp):
        self.manifest['jwt_exp_seconds'] = jwt_exp
        self.record()
        bootstrap_password, owner_password, jwt_secret = (secrets.token_urlsafe(40) for _ in range(3))
        user_password = secrets.token_urlsafe(24)
        self.secrets += [bootstrap_password, owner_password, jwt_secret, user_password]

        # The signing key: generated by the pinned jose-util into the private directory, then given the key_ops
        # GoTrue needs, as in the observed dedicated-owner ES256 probe (exactly one key may sign).
        kid = 'aya-core-ra-' + secrets.token_hex(6)
        private_key = self.track('jwk-sig-' + kid + '-priv.json')
        self.track('jwk-sig-' + kid + '-pub.json', kind='public')
        generated = subprocess.run([str(jose), 'generate-key', '--use', 'sig', '--alg', 'ES256', '--kid', kid],
                                   cwd=self.private, capture_output=True, text=True, timeout=30)
        if generated.returncode or not private_key.is_file():
            raise RuntimeError('jose-util could not generate the signing key')
        jwk = json.loads(private_key.read_text())
        if jwk.get('kty') != 'EC' or jwk.get('crv') != 'P-256' or not jwk.get('d') or jwk.get('kid') != kid:
            raise RuntimeError('jose-util did not generate a private P-256 key under its kid')
        self.secrets.append(jwk['d'])
        jwk.update(alg='ES256', use='sig', key_ops=['sign', 'verify'])
        keys = json.dumps([jwk], separators=(',', ':'))
        self.secrets.append(keys)

        internal = self.network(self.label + '-int', internal=True)
        published = self.network(self.label + '-pub', internal=False)

        # PostgreSQL: the observed probe's nonroot, read-only, unprivileged setup on the internal network only.
        database = self.label + '-db'
        pg_env = self.write('postgres.env', envfile({'POSTGRES_USER': 'postgres', 'POSTGRES_DB': 'aya_auth',
                                                     'POSTGRES_PASSWORD': bootstrap_password}))
        self.container(database, 'run', '-d', '--pull=never', '--name', database, '--label', LABEL + '=' + self.label,
                       '--network', internal, '--network-alias', 'db', '--user', '999:999', '--read-only',
                       '--cap-drop', 'ALL', '--security-opt', 'no-new-privileges:true', '--memory', '512m', '--cpus', '1',
                       '--tmpfs', '/var/lib/postgresql/data:uid=999,gid=999,mode=0700,size=256m',
                       '--tmpfs', '/var/run/postgresql:uid=999,gid=999,mode=0775', '--tmpfs', '/tmp:mode=1777',
                       '--env-file', str(pg_env), POSTGRES_IMAGE)
        self.discard('postgres.env')
        wait_for(60, lambda: docker('exec', database, 'pg_isready', '-U', 'postgres', '-d', 'aya_auth').returncode == 0,
                 'the owned PostgreSQL did not become ready')
        # GoTrue's runtime queries name its tables unqualified, so the owner's sessions in aya_auth search its auth
        # schema: the pinned hack/init_postgres.sql's search_path for its auth admin role, here scoped to one
        # database. A per-role setting only; it grants nothing and leaves every role attribute as created.
        require(docker('exec', '-i', database, 'psql', '-X', '-q', '-v', 'ON_ERROR_STOP=1', '-U', 'postgres', '-d',
                       'aya_auth', input=(
                           "CREATE ROLE aya_auth_owner LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS "
                           "PASSWORD '" + owner_password + "';\n"
                           "ALTER DATABASE aya_auth OWNER TO aya_auth_owner;\n"
                           "REVOKE CREATE ON SCHEMA public FROM PUBLIC;\n"
                           "CREATE SCHEMA auth AUTHORIZATION aya_auth_owner;\n"
                           "ALTER ROLE aya_auth_owner IN DATABASE aya_auth SET search_path = auth;\n")),
                'bootstrap the dedicated non-superuser auth owner')

        # GoTrue: the observed probe's settings, its API published on literal loopback only. It is created on the
        # bridge network that carries the published port, joined to the internal network, and only then started.
        port = free_port()
        base = 'http://127.0.0.1:' + str(port)
        dsn = 'postgresql://aya_auth_owner:' + owner_password + '@db:5432/aya_auth?sslmode=disable'
        self.secrets.append(dsn)
        auth_env = self.write('auth.env', envfile({
            'DATABASE_URL': dsn, 'GOTRUE_DB_DRIVER': 'postgres', 'GOTRUE_DB_NAMESPACE': 'auth',
            'GOTRUE_DB_MAX_POOL_SIZE': '5', 'GOTRUE_SITE_URL': base, 'API_EXTERNAL_URL': base,
            'GOTRUE_API_HOST': '0.0.0.0', 'PORT': '9999', 'GOTRUE_JWT_SECRET': jwt_secret, 'GOTRUE_JWT_KEYS': keys,
            'GOTRUE_JWT_AUD': AUDIENCE, 'GOTRUE_JWT_ADMIN_ROLES': 'service_role', 'GOTRUE_JWT_ISSUER': ISSUER,
            'GOTRUE_JWT_EXP': str(jwt_exp), 'GOTRUE_DISABLE_SIGNUP': 'true', 'GOTRUE_EXTERNAL_EMAIL_ENABLED': 'true',
            'GOTRUE_MAILER_AUTOCONFIRM': 'false', 'GOTRUE_EXTERNAL_PHONE_ENABLED': 'false',
            'GOTRUE_EXTERNAL_ANONYMOUS_USERS_ENABLED': 'false', 'GOTRUE_TRACING_ENABLED': 'false',
            'GOTRUE_METRICS_ENABLED': 'false'}))
        auth = self.label + '-auth'
        self.container(auth, 'create', '--pull=never', '--name', auth, '--label', LABEL + '=' + self.label,
                       '--network', published, '--publish', '127.0.0.1:' + str(port) + ':9999', '--read-only',
                       '--cap-drop', 'ALL', '--security-opt', 'no-new-privileges:true', '--memory', '512m', '--cpus', '1',
                       '--env-file', str(auth_env), AUTH_IMAGE)
        self.discard('auth.env')
        require(docker('network', 'connect', internal, auth), 'connect the owned Auth to the internal network')
        require(docker('start', auth), 'start the owned Auth')
        self.manifest.update(auth_base_url=base, auth_port=port)
        self.record()

        def answering():
            if docker('container', 'inspect', '--format', '{{.State.Running}}', auth).stdout.strip() != 'true':
                raise RuntimeError('the owned Auth exited while migrating as the dedicated owner')
            return http_json('GET', base + '/health')[0] == 200

        wait_for(90, answering, 'the owned Auth did not answer on its loopback port')
        if http_json('GET', base + '/health')[1].get('version') != 'v2.197.0':
            raise RuntimeError('the owned Auth is not GoTrue v2.197.0')
        status, published_keys = http_json('GET', base + '/.well-known/jwks.json')
        observed = published_keys.get('keys', []) if status == 200 else []
        if not (len(observed) == 1 and observed[0].get('kid') == kid and observed[0].get('alg') == 'ES256' and
                observed[0].get('x') == jwk['x'] and observed[0].get('y') == jwk['y'] and 'd' not in observed[0]):
            raise RuntimeError('the owned Auth does not publish exactly its public ES256 signing key')
        # With the migrations applied, a session of the dedicated owner in aya_auth (over the container's local
        # socket: no password, nothing printed) must resolve GoTrue's unqualified table names in its auth schema.
        lookup = require(docker('exec', database, 'psql', '-X', '-At', '-v', 'ON_ERROR_STOP=1', '-U', 'aya_auth_owner',
                                '-d', 'aya_auth', '-c',
                                "SELECT current_schema() = 'auth' AND to_regclass('identities') IS NOT NULL "
                                "AND to_regclass('identities') = to_regclass('auth.identities')"),
                         'check the dedicated owner search path')
        if lookup.stdout.strip() != 't':
            raise RuntimeError("the dedicated owner's sessions do not resolve GoTrue tables in its auth schema")

        # The server-only admin credential: a service_role JWT that jose-util signs with Auth's own key.
        issued = int(time.time())
        admin = jose_sign(jose, private_key, {'role': 'service_role', 'iss': ISSUER, 'iat': issued,
                                              'exp': issued + TOKEN_LIFETIME})
        self.secrets.append(admin)
        admin_file = self.write('admin-key', admin)

        # One admin-confirmed synthetic user, then one password session of it, whose claims the wrong-claim
        # tokens copy with exactly one claim changed.
        # The user is created with its role named explicitly: the pinned admin.go (lines 511-515) otherwise falls
        # back to the deprecated JWT_DEFAULT_GROUP_NAME, which this fixture does not set. An ordinary app user is
        # "authenticated"; service_role stays the server-only admin credential's alone.
        email = 'aya-it-' + secrets.token_hex(6) + '@example.test'
        status, user = http_json('POST', base + '/admin/users',
                                 {'email': email, 'password': user_password, 'email_confirm': True,
                                  'role': 'authenticated'}, bearer=admin)
        if status != 200 or not user.get('id'):
            raise RuntimeError('the owned Auth did not create the synthetic user (status %d)' % status)
        self.manifest['synthetic_users'].append({'id': user['id'], 'email': email,
                                                 'removed_with': 'the owned PostgreSQL container'})
        self.record()
        status, session = http_json('POST', base + '/token?grant_type=password',
                                    {'email': email, 'password': user_password})
        template = session.get('access_token', '') if status == 200 else ''
        if template.count('.') != 2:
            raise RuntimeError('the owned Auth did not sign the synthetic user in (status %d)' % status)
        self.secrets += [template, session.get('refresh_token', '')]
        claims = claims_of(template)
        audience = claims.get('aud')
        if not (claims.get('iss') == ISSUER and AUDIENCE in (audience if isinstance(audience, list) else [audience]) and
                claims.get('role') == 'authenticated' and claims.get('sub') == user['id'] and claims.get('session_id') and
                any(entry.get('method') == 'password' for entry in claims.get('amr', []))):
            raise RuntimeError('the owned Auth issued a password session unlike the one this fixture expects')
        # The lifetime asked for is the one real sessions get: the reply's expires_in and the token's own times.
        if not (session.get('expires_in') == jwt_exp and isinstance(claims.get('exp'), int) and
                isinstance(claims.get('iat'), int) and claims['exp'] - claims['iat'] == jwt_exp):
            raise RuntimeError('the owned Auth did not issue a %d s password session' % jwt_exp)
        wrong = {}
        for name, claim, value in WRONG:
            changed = dict(claims, exp=issued + TOKEN_LIFETIME)
            changed[claim] = value
            wrong[name] = jose_sign(jose, private_key, changed)
            self.secrets.append(wrong[name])

        values = {'AYA_SUPABASE_URL': base, 'AYA_SUPABASE_ISSUER': ISSUER, 'AYA_SUPABASE_AUDIENCE': AUDIENCE,
                  'AYA_SUPABASE_ADMIN_KEY_FILE': str(admin_file), 'AYA_FIXTURE_USER_ID': user['id'],
                  'AYA_FIXTURE_USER_EMAIL': email, 'AYA_FIXTURE_USER_PASSWORD': user_password}
        values.update(('AYA_FIXTURE_TOKEN_WRONG_' + name, token) for name, token in wrong.items())
        fixture_env = self.write('fixture.env', envfile(values))
        self.manifest.update(state='running', issuer=ISSUER, audience=AUDIENCE, signing_kid=kid,
                             fixture_env=str(fixture_env), admin_key_file=str(admin_file), ready_at=now_iso())
        self.record()

    def save_logs(self):
        for entry in self.manifest['containers']:
            logs = docker('logs', entry.get('id') or entry['name'])
            if logs.returncode == 0:
                self.write(entry['name'] + '-redacted.log', self.redact(logs.stdout + '\n' + logs.stderr), kind='log')

    def cleanup(self, keep_logs):
        report = {'containers': [], 'networks': [], 'files': []}
        for entry in reversed(self.manifest['containers']):
            report['containers'].append({'name': entry['name'], 'result': remove('container', entry, self.label)})
        for entry in reversed(self.manifest['networks']):
            report['networks'].append({'name': entry['name'], 'result': remove('network', entry, self.label)})
        kept = []
        for entry in self.manifest['files']:
            if keep_logs and entry['kind'] == 'log':
                kept.append(entry)
                continue
            path = self.private / entry['name']
            existed = path.exists()
            path.unlink(missing_ok=True)
            report['files'].append({'name': entry['name'], 'result': 'removed' if existed else 'absent'})
        self.manifest['files'] = kept
        self.record()
        return report

    def fail(self, error):
        try:
            self.save_logs()
        finally:
            self.manifest['cleanup'] = self.cleanup(keep_logs=True)
            self.manifest.update(state='failed; its resources and secret files were removed',
                                 failure=self.redact(str(error) or type(error).__name__), failed_at=now_iso())
            self.record()

    def summary(self):
        m = self.manifest
        return {'label': m['label'], 'state': m['state'], 'runtime_directory': m['runtime_directory'],
                'fixture_env': m.get('fixture_env'), 'auth_base_url': m.get('auth_base_url'), 'issuer': m.get('issuer'),
                'audience': m.get('audience'), 'signing_kid': m.get('signing_kid'),
                'jwt_exp_seconds': m.get('jwt_exp_seconds', JWT_EXP_DEFAULT),
                'containers': [entry['name'] for entry in m['containers']],
                'networks': [entry['name'] for entry in m['networks']],
                'synthetic_user_ids': [entry['id'] for entry in m['synthetic_users']],
                'secrets': 'only in 0600 files under runtime_directory (jose-util key files 0400); never printed'}


def write_evidence(fixture, suffix, **extra):
    ensure_runtime()
    path = EVIDENCE / ('real-auth-fixture-' + fixture.label + suffix + '.json')
    path.write_text(json.dumps(dict(fixture.summary(), at=now_iso(), **extra), indent=2) + '\n')


def up(args):
    binary = jose_util(args.jose_util)
    for image in (POSTGRES_IMAGE, AUTH_IMAGE):
        if docker('image', 'inspect', '--format', '{{.Id}}', image).returncode:
            raise SystemExit('a pinned image is not cached locally, and this helper never pulls: ' + image)
    fixture = Fixture.new()
    try:
        fixture.create(binary, args.jwt_exp)
    except BaseException as error:
        fixture.fail(error)
        write_evidence(fixture, '-failed', failure=fixture.manifest['failure'], cleanup=fixture.manifest['cleanup'])
        print(json.dumps(dict(fixture.summary(), failure=fixture.manifest['failure'],
                              cleanup=fixture.manifest['cleanup']), indent=2))
        return 1
    write_evidence(fixture, '')
    print(json.dumps(fixture.summary(), indent=2))
    return 0


def status(args):
    fixture = Fixture.load(args.runtime_directory)
    report = {'label': fixture.label, 'state': fixture.manifest['state'], 'containers': {}}
    for entry in fixture.manifest['containers']:
        inspected = docker('container', 'inspect', '--format', '{{.State.Status}}', entry.get('id') or entry['name'])
        report['containers'][entry['name']] = inspected.stdout.strip() if inspected.returncode == 0 else 'absent'
    base = fixture.manifest.get('auth_base_url')
    if base:
        code, doc = http_json('GET', base + '/health')
        report['auth_health'] = {'status': code, 'version': doc.get('version')}
    print(json.dumps(report, indent=2))
    return 0


def down(args):
    """Removes what the manifest records. If any removal is incomplete, the manifest (identifiers only, never a secret) and its
    directory stay so that running `down` again can finish; the secret files are removed either way."""
    fixture = Fixture.load(args.runtime_directory)
    report = fixture.cleanup(keep_logs=False)
    ok = all(item['result'] in ('removed', 'absent') for group in report.values() for item in group)
    if ok:
        fixture.manifest.update(state='removed', removed_at=now_iso())
    else:
        fixture.manifest.update(state='removal incomplete', removal_attempted_at=now_iso())
        fixture.record()
    write_evidence(fixture, '-cleanup', cleanup=report)
    if ok:
        for name in ('manifest.json', 'manifest.json.tmp'):
            (fixture.private / name).unlink(missing_ok=True)
    leftovers = sorted(path.name for path in fixture.private.iterdir())
    if not leftovers:
        fixture.private.rmdir()
    summary = {'label': fixture.label, 'cleanup': report, 'runtime_directory_removed': not leftovers, 'leftover_files': leftovers}
    if not ok:
        summary['retry'] = 'run down again with the same runtime directory once the failed removals can succeed'
    print(json.dumps(summary, indent=2))
    return 0 if ok and not leftovers else 1


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    commands = parser.add_subparsers(dest='command', required=True)
    start = commands.add_parser('up')
    start.add_argument('--jose-util', default=str(JOSE_UTIL))
    start.add_argument('--jwt-exp', type=jwt_exp, default=JWT_EXP_DEFAULT, metavar='SECONDS',
                       help='access-token lifetime of real sessions, %d to %d s (default %d)' % (JWT_EXP_RANGE + (JWT_EXP_DEFAULT,)))
    commands.add_parser('build-jose-util')
    for name in ('status', 'down'):
        commands.add_parser(name).add_argument('runtime_directory')
    args = parser.parse_args()
    return {'up': up, 'status': status, 'down': down, 'build-jose-util': build_jose_util}[args.command](args)


